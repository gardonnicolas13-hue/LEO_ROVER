  /* --------------------------------------------------------------------------
     I18N ENGINE
  --------------------------------------------------------------------------- */
  var I18N = {
    current: (typeof localStorage !== 'undefined' && localStorage.getItem('leo_lang_v2')) || 'en',

    /** Returns the translation for a key (falls back to EN if missing in current language). */
    t: function (key) {
      var s = T[this.current] && T[this.current][key];
      if (s === undefined) s = T.en[key];
      return s !== undefined ? s : key;
    },

    /** Change language, persist to localStorage, apply to DOM. */
    set: function (lang) {
      if (!T[lang]) { console.warn('[I18N] unknown language:', lang); return; }
      this.current = lang;
      if (typeof localStorage !== 'undefined') localStorage.setItem('leo_lang_v2', lang);
      this.apply();
    },

    /** Alias for set() — compatible with external callers. */
    changeLanguage: function (lang) { this.set(lang); },

    /** Scan all [data-i18n] / [data-i18n-html] elements and update the DOM. */
    apply: function () {
      var lang = this.current;

      /* Plain-text elements */
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var val = I18N.t(el.dataset.i18n);
        if (el.tagName === 'INPUT') {
          el.placeholder = val;
        } else {
          el.textContent = val;
        }
      });

      /* innerHTML elements (keys whose value may contain HTML tags) */
      document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        el.innerHTML = I18N.t(el.dataset.i18nHtml);
      });

      /* Language toggle buttons: active / inactive */
      document.querySelectorAll('.lang-btn').forEach(function (btn) {
        var active = btn.dataset.lang === lang;
        btn.className = 'lang-btn rounded-md px-2 py-1 text-xs font-bold transition-all '
          + (active
            ? 'bg-accent text-white shadow-neon'
            : 'text-zinc-400 hover:text-white hover:bg-white/10');
      });

      /* Title attributes */
      document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
        el.title = I18N.t(el.dataset.i18nTitle);
      });

      /* Document lang attribute */
      document.documentElement.lang = lang === 'fr' ? 'fr' : 'en';
    },
  };

  window.I18N = I18N;
